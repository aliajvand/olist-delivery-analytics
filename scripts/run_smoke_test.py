"""End-to-end verification that runs without the 120 MB Kaggle download.

Builds an Olist-SHAPED synthetic dataset, pushes it through cleaning, features
and the modeling contract, then writes reports/pipeline_smoke_test.md.

The numbers in that report describe the PIPELINE, not the Brazilian market.
Nothing produced here may be quoted as an analysis result. Real figures come
from `make pipeline` once data/raw holds the nine genuine Olist CSVs.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "scripts")]

import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import HistGradientBoostingClassifier

from make_sample_data import build
from olist import cleaning, features, modeling as ml

N_ORDERS = 8000
SEED = 7
COST_FP, COST_FN = 1.0, 4.0     # stated assumption: a missed late delivery hurts more
CAPACITY = 0.20                  # share of orders operations can actually intervene on


def main() -> int:
    t0 = time.time()
    raw = build(n_orders=N_ORDERS, seed=SEED)
    clean, clean_audits = cleaning.build_clean_tables(raw)
    tables, feature_audits = features.build_feature_tables(clean)

    grain = features.grain_audit(tables)
    recon = features.feature_reconciliation(clean, tables)
    base = tables["order_model_base"]
    cols = [c for c in features.PURCHASE_TIME_FEATURES if c in base.columns]
    audit = ml.leakage_audit(cols, target="late_delivery_flag")
    data = ml.chronological_split(base, cols, "late_delivery_flag")

    candidates = {
        **ml.baseline_classifiers(data.y_train),
        "logreg": LogisticRegression(max_iter=1000, class_weight="balanced", random_state=42),
        "hist_gbm": HistGradientBoostingClassifier(max_leaf_nodes=31, learning_rate=0.08,
                                                   max_iter=250, random_state=42),
    }
    table, fitted = ml.compare_candidates(candidates, data, task="classification")
    champion = table.sort_values("pr_auc", ascending=False).iloc[0]

    pipe = fitted[champion["model"]]
    proba = pipe.predict_proba(ml.to_sklearn_frame(data.X_test))[:, 1]
    policy = ml.threshold_policy(data.y_test.astype(int), proba, COST_FP, COST_FN)
    capacity = ml.capacity_policy(data.y_test.astype(int), proba, CAPACITY)

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    table.round(4).to_csv(out / "smoke_test_leaderboard.csv", index=False)
    policy.round(4).to_csv(out / "smoke_test_threshold_policy.csv", index=False)

    lines = [
        "# Pipeline smoke test",
        "",
        "> **Synthetic data.** Every number on this page describes the pipeline, not the",
        "> Brazilian e-commerce market. `scripts/make_sample_data.py` generates",
        "> Olist-shaped rows so the whole project can be verified without the Kaggle",
        "> download. Reported analysis comes from `make pipeline` on the nine real CSVs.",
        "",
        f"Generated by `scripts/run_smoke_test.py` in {time.time() - t0:.1f}s.",
        "",
        "## What was exercised",
        "",
        f"| Stage | Result |",
        f"|---|---|",
        f"| Synthetic orders generated | {N_ORDERS:,} |",
        f"| Clean tables built | {len(clean)} |",
        f"| Feature tables built | {len(tables)} |",
        f"| Declared-grain checks | {(grain['status'] == 'PASS').sum()}/{len(grain)} PASS |",
        f"| Money and count reconciliation | {(recon['status'] == 'PASS').sum()}/{len(recon)} PASS |",
        f"| Leakage audit on the feature contract | {(audit['verdict'] == 'allowed').sum()}/{len(audit)} allowed |",
        f"| Model base shape | {base.shape[0]:,} x {base.shape[1]} |",
        f"| Chronological split | train {len(data.X_train):,} / valid {len(data.X_valid):,} / test {len(data.X_test):,} |",
        "",
        "## Candidate comparison (synthetic, illustrative only)",
        "",
        table.round(4).to_markdown(index=False),
        "",
        f"Champion by PR-AUC: **{champion['model']}**. Both trivial baselines stay in the",
        "table on purpose: a model that cannot beat the prior has no business being deployed.",
        "",
        "## Decision policies",
        "",
        f"Cost assumption: false alarm {COST_FP}, missed late delivery {COST_FN}.",
        "",
        policy.head(12).round(4).to_markdown(index=False),
        "",
        f"At {int(CAPACITY * 100)}% intervention capacity: "
        + ", ".join(f"{k} = {round(v, 4)}" for k, v in capacity.items()),
        "",
        "## Reproduce",
        "",
        "```bash",
        "make sample     # synthetic end-to-end run",
        "make test       # 34 tests over cleaning, features and the modeling contract",
        "make pipeline   # the real thing, once data/raw holds the nine Olist CSVs",
        "```",
    ]
    (out / "pipeline_smoke_test.md").write_text("\n".join(lines))
    print("\n".join(lines[:26]))
    print(f"\nwrote {out/'pipeline_smoke_test.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
